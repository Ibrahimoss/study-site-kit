"""Coverage-gap report: where the study material is thin, per unit and per lesson section.

engine/build.py calls report() after the data build; it writes <out_dir>/coverage.md and coverage.csv and returns a
one-line summary.

A quiz item or flashcard belongs to every section whose `slides` list its ref page (the unit's own deck), or to the
section it names with `sec`. A short belongs to the sections in its script's "sections" tags. Exam weight comes from
exam_blueprint.json when there is one: the marks of each slot, split over the units whose practice items fill it.
"""
import csv
import os


def report(units, shorts, blueprint, out_dir, shorts_on=True):
    """units: the built unit dicts (id, deck, sections, quiz, cards, practice); shorts: [{id, unit, sections}].
    shorts_on: False when the course has shorts turned off, so nothing in the report talks about shorts."""
    if not shorts_on:
        shorts = []
    order = [u["id"] for u in units]
    byid = {u["id"]: u for u in units}
    marks = {u: 0.0 for u in order}
    total_marks = 0
    if blueprint:
        slot_units = {}
        for u in units:
            for p in u.get("practice", []):
                if p.get("slot"):
                    slot_units.setdefault(p["slot"], set()).add(u["id"])
        for q in blueprint.get("questions", []):
            for part in q.get("parts", []):
                slots = part["slot"] if isinstance(part["slot"], list) else [part["slot"]]
                us = set().union(*(slot_units.get(x, set()) for x in slots))
                total_marks += part.get("maxMarks", 0)
                for u in us:
                    marks[u] += part.get("maxMarks", 0) / len(us)

    rows, flags = [], []
    for uid in order:
        d = byid[uid]
        for i, s in enumerate(d["sections"]):
            pages = set(s.get("slides") or [])

            def hit(it, i=i, pages=pages):
                if it.get("sec") is not None:
                    return int(it["sec"]) == i + 1
                r = it.get("ref") or {}
                return r.get("deck") == d["deck"] and r.get("page") in pages
            nq = sum(1 for q in d["quiz"] if hit(q))
            nc = sum(1 for c in d["cards"] if hit(c))
            ids = [x["id"] for x in shorts if x["unit"] == uid and s["title"] in (x.get("sections") or [])]
            rows.append({"unit": uid, "n": i + 1, "section": s["title"], "priority": s.get("priority") or "", "slides": len(pages),
                         "quiz": nq, "cards": nc, "shorts": len(ids), "short_ids": " ".join(ids)})
            high = s.get("priority") == "high"
            if shorts and high and not ids:
                flags.append((0, uid, s["title"], "high-priority section with no short"))
            elif high and pages and (nq == 0 or nc == 0):
                flags.append((1, uid, s["title"], "high-priority section with " + ("no quiz items" if nq == 0 else "no cards") + " on its slides"))
            elif not high and not ids and nq + nc == 0 and pages:
                flags.append((3, uid, s["title"], "no short, quiz item or card" if shorts else "no quiz item or card"))
        if shorts and total_marks:
            nshorts = sum(1 for x in shorts if x["unit"] == uid)
            share_s, share_m = nshorts / max(1, len(shorts)), marks[uid] / total_marks
            if share_m and share_s < share_m * 0.6:
                flags.append((2, uid, "(unit)", f"{nshorts} shorts = {share_s:.0%} of shorts, but {share_m:.0%} of exam marks"))

    flags.sort()
    os.makedirs(out_dir, exist_ok=True)
    fields = ["unit", "n", "section", "priority", "slides", "quiz", "cards"] + (["shorts", "short_ids"] if shorts_on else [])
    with open(os.path.join(out_dir, "coverage.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)

    out = ["# Coverage report", "", "Generated by `engine/build.py`. Quiz items and cards count for a section when their",
           "slide reference is one of the section's slides (or they name the section with `sec`)" +
           ("; shorts count by their `sections` tags." if shorts_on else "."), "", "## Flags, worst first", ""]
    names = {0: "No short", 1: "Thin", 2: "Unit share", 3: "Empty"}
    out += [f"- **{names[k]}** · {u} · {t}: {m}" for k, u, t, m in flags] or ["- none"]
    sh = " shorts |" if shorts_on else ""
    out += ["", "## Per unit", "", "| unit | sections |" + sh + " quiz | cards | practice | exam marks |", "|---" * (6 + shorts_on) + "|"]
    for uid in order:
        d = byid[uid]
        out.append(f"| {uid} | {len(d['sections'])} |" + (f" {sum(1 for x in shorts if x['unit'] == uid)} |" if shorts_on else "") +
                   f" {len(d['quiz'])} | {len(d['cards'])} | {len(d.get('practice', []))} | " +
                   (f"{marks[uid]:.1f} of {total_marks}" if total_marks else "-") + " |")
    for uid in order:
        out += ["", f"## {uid}", "", "| # | section | priority | quiz | cards |" + sh, "|---" * (5 + shorts_on) + "|"]
        for r in rows:
            if r["unit"] == uid:
                out.append(f"| {r['n']} | {r['section']} | {r['priority']} | {r['quiz']} | {r['cards']} |" +
                           (f" {r['shorts']} {r['short_ids']} |" if shorts_on else ""))
    open(os.path.join(out_dir, "coverage.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")

    counts = {k: sum(1 for f in flags if f[0] == k) for k in names}
    if not shorts_on:
        return f"coverage: {len(rows)} sections; {counts[1]} thin, {counts[3]} empty"
    return (f"coverage: {len(rows)} sections, {sum(1 for r in rows if r['shorts'])} with a short; "
            f"{counts[0]} high-priority sections without a short, {counts[1]} thin, {counts[2]} units under-covered, {counts[3]} empty")
